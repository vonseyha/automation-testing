"""
Machine-readable Test Case Catalog and Inventory.
Per Sections 6, 8, 9, 10, 11:
- Every test case maps to a discovered feature and real execution runner.
- Distinguishes lifecycle status: DISCOVERED, PLANNED, IMPLEMENTED, EXECUTABLE, EXECUTED, PASSED, FAILED, BLOCKED.
- Enables bi-directional traceability (Feature <-> Test Case).
"""

from dataclasses import asdict, dataclass
from enum import Enum
from typing import Any, Dict, List, Optional


class LifecycleStatus(str, Enum):
    DISCOVERED = "DISCOVERED"
    PLANNED = "PLANNED"
    IMPLEMENTED = "IMPLEMENTED"
    EXECUTABLE = "EXECUTABLE"
    EXECUTED = "EXECUTED"
    PASSED = "PASSED"
    FAILED = "FAILED"
    BLOCKED = "BLOCKED"


@dataclass
class DiscoveredTestCase:
    test_case_id: str
    feature_id: str
    module: str
    test_name: str
    description: str
    test_type: str
    priority: str
    preconditions: str
    steps: List[str]
    expected_result: str
    runner: str
    status: LifecycleStatus
    evidence: str

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["status"] = self.status.value if hasattr(self.status, "value") else str(self.status)
        return d


