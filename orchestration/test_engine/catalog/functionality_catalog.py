FUNCTIONALITY_CATALOG: Dict[str, DiscoveredFeature] = {
    item["feature_id"]: DiscoveredFeature(**item) for item in RAW_FEATURES
}


def get_feature(feature_id: str) -> Optional[DiscoveredFeature]:
    return FUNCTIONALITY_CATALOG.get(feature_id)


def list_features() -> List[DiscoveredFeature]:
    return list(FUNCTIONALITY_CATALOG.values())


def list_features_by_module(module: str) -> List[DiscoveredFeature]:
    return [f for f in FUNCTIONALITY_CATALOG.values() if f.module.lower() == module.lower()]


def list_features_by_criticality(criticality: str) -> List[DiscoveredFeature]:
    return [f for f in FUNCTIONALITY_CATALOG.values() if f.business_criticality.upper() == criticality.upper()]
